// Checks that ml.json and en.json have the same keys, then regenerates
// docs/ml-review.md: every Malayalam string, with its English source and
// review status. To mark a string as reviewed, add its key to
// docs/ml-review.status.json, e.g. { "nav.services": "approved" }.
//
// Run: npm run i18n:check
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const read = (p) => JSON.parse(readFileSync(resolve(root, p), "utf8"));

const flatten = (obj, prefix = "") =>
  Object.entries(obj).flatMap(([k, v]) =>
    v && typeof v === "object" ? flatten(v, `${prefix}${k}.`) : [[`${prefix}${k}`, String(v)]],
  );

const en = new Map(flatten(read("messages/en.json")));
const ml = new Map(flatten(read("messages/ml.json")));
const statusPath = "docs/ml-review.status.json";
const status = existsSync(resolve(root, statusPath)) ? read(statusPath) : {};

// Bilingual { en, ml } strings inside src/data/*.ts (Node 24 runs TS directly).
import { readdirSync } from "node:fs";
import { pathToFileURL } from "node:url";
const dataDir = resolve(root, "src/data");
for (const file of readdirSync(dataDir).filter((f) => f.endsWith(".ts") && f !== "types.ts")) {
  const mod = await import(pathToFileURL(resolve(dataDir, file)).href);
  const walk = (value, path) => {
    if (Array.isArray(value)) return value.forEach((v, i) => walk(v, `${path}[${v?.slug ?? v?.id ?? i}]`));
    if (value && typeof value === "object") {
      if (typeof value.en === "string" && typeof value.ml === "string") {
        ml.set(path, value.ml);
        en.set(path, value.en);
        return;
      }
      for (const [k, v] of Object.entries(value)) walk(v, `${path}.${k}`);
    }
  };
  for (const [name, value] of Object.entries(mod)) if (typeof value !== "function" && !name.endsWith("BySlug")) walk(value, `data/${file.replace(".ts", "")}:${name}`);
}

const missingInMl = [...en.keys()].filter((k) => !ml.has(k));
const extraInMl = [...ml.keys()].filter((k) => !en.has(k));

const esc = (s) => s.replace(/\|/g, "\\|").replace(/\n/g, " ");
const rows = [...ml.entries()].map(
  ([key, text]) =>
    `| \`${key}\` | ${esc(text)} | ${esc(en.get(key) ?? "—")} | ${status[key] ?? "needs native-speaker review"} |`,
);
const pending = [...ml.keys()].filter((k) => status[k] !== "approved").length;

writeFileSync(
  resolve(root, "docs/ml-review.md"),
  `# Malayalam review tracker

Generated by \`npm run i18n:check\` — do not edit by hand.
Every Malayalam string on the site, from \`messages/ml.json\`. Long-form Malayalam
in \`content/**/ml/*.mdx\` is listed separately at the bottom as it is added.

To approve a string, add its key to \`${statusPath}\` with the value \`"approved"\`
(or \`"changed"\` if you edited the Malayalam), then re-run the script.

**${pending} of ${ml.size} strings still need native-speaker review.**

| Key | Malayalam | English source | Status |
|---|---|---|---|
${rows.join("\n")}
`,
);

if (missingInMl.length || extraInMl.length) {
  if (missingInMl.length) console.error("Missing in ml.json:", missingInMl);
  if (extraInMl.length) console.error("Not in en.json:", extraInMl);
  process.exit(1);
}
console.log(`i18n OK — ${ml.size} keys in both languages, ${pending} awaiting review.`);
